import type { Metadata, Viewport } from "next"
import { Geist, Geist_Mono, Vazirmatn  } from "next/font/google"
import "./globals.css"
import Providers from "@/app/components/Providers"
import { themeInitScript } from "@/app/components/ThemeProvider"

const geistSans = Geist({
   variable: "--font-geist-sans",
   subsets: ["latin"],
})

const geistMono = Geist_Mono({
   variable: "--font-geist-mono",
   subsets: ["latin"],
})

const vazirmatn = Vazirmatn({
   variable: "--font-vazirmatn",
   // "arabic" is required — "latin" alone never loads Persian glyphs.
   subsets: ["arabic", "latin"],
})

export const metadata: Metadata = {
   title: "Shopify Starter",
   description: "Generated by create next app",
}

export const viewport: Viewport = {
   width: "device-width",
   initialScale: 1,
   // Matches the page background so mobile browser chrome blends in.
   themeColor: [
      { media: "(prefers-color-scheme: light)", color: "#f7fafc" },
      { media: "(prefers-color-scheme: dark)", color: "#0b1220" },
   ],
}

export default function RootLayout({ children }: { children: React.ReactNode }) {
   return (
      <html lang="en" suppressHydrationWarning className={`${geistSans.variable} ${geistMono.variable} ${vazirmatn.variable} h-full antialiased`}>
         <head>
            {/* Runs before paint so dark-mode visitors never see a white flash. */}
            <script dangerouslySetInnerHTML={{ __html: themeInitScript }} />
         </head>
         <body className="min-h-full flex flex-col">
            <Providers>{children}</Providers>
         </body>
      </html>
   )
}
